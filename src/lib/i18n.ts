const LOADERS: Record<Exclude<Locale, "pt">, () => Promise<{ default: Record<string, string> }>> = {
  en: () => import("./locales/en"),
  es: () => import("./locales/es"),
  fr: () => import("./locales/fr"),
};

const loading: Partial<Record<Locale, Promise<void>>> = {};

// Carrega o idioma pedido (se ainda não estiver carregado). Nunca rebenta:
// se falhar (rede), a app continua em PT e tenta outra vez na próxima vez.
export function loadLocale(l: Locale): Promise<void> {
  if (l === "pt" || !(l in LOADERS) || Object.keys(TRANSLATIONS[l] ?? {}).length > 0) {
    return Promise.resolve();
  }
  loading[l] ??= LOADERS[l as Exclude<Locale, "pt">]()
    .then((m) => {
      TRANSLATIONS[l] = m.default;
      window.dispatchEvent(new Event("localechange"));
    })
    .catch((err) => {
      delete loading[l];
      console.warn("i18n: falha a carregar idioma", l, err);
    });
  return loading[l]!;
}

export function t(key: string, locale?: Locale): string {
  const l = locale ?? getLocale();
  // TRANSLATIONS[l] pode não existir se algures ficar gravado um código
  // de idioma antigo/inválido (ex: dados criados antes desta lista ter
  // sido reduzida aos 4 idiomas suportados) — sem este fallback isto
  // rebentava a app inteira com um ecrã em branco.
  return TRANSLATIONS[l]?.[key] ?? TRANSLATIONS["pt"][key] ?? key;
}

