export function t(key: string, locale?: Locale): string {
  const l = locale ?? getLocale();
  // TRANSLATIONS[l] pode não existir se algures ficar gravado um código
  // de idioma antigo/inválido (ex: dados criados antes desta lista ter
  // sido reduzida aos 4 idiomas suportados) — sem este fallback isto
  // rebentava a app inteira com um ecrã em branco.
  return TRANSLATIONS[l]?.[key] ?? TRANSLATIONS["pt"][key] ?? key;
}

