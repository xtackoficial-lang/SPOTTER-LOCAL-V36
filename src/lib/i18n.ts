// ────────────────────────────────────────────────────────────
// Hook reactivo de idioma.
// Antes, mudar o idioma (setLocale) gravava em localStorage e disparava
// o evento "localechange", mas NENHUM componente da app o escutava — o
// resto do texto continuava com a tradução do render anterior, dando a
// sensação de que "trocar idioma não funciona". Este hook resolve isso:
// qualquer componente que o use re-renderiza automaticamente sempre que
// o idioma muda, em qualquer parte da app (e mesmo entre separadores,
// via evento "storage").
// ────────────────────────────────────────────────────────────
export function useLocale(): [Locale, (l: Locale) => void] {
  const [locale, setLocaleState] = useState<Locale>(getLocale());

  useEffect(() => {
    const sync = () => setLocaleState(getLocale());
    window.addEventListener("localechange", sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener("localechange", sync);
      window.removeEventListener("storage", sync);
    };
  }, []);

  const change = useCallback((l: Locale) => {
    setLocale(l);
    setLocaleState(l);
  }, []);

  return [locale, change];
}

// Hook de tradução conveniente: useT() devolve a função t() já reactiva
// ao idioma actual, para usar como `const tr = useT(); tr("home")`.
export function useT() {
  const [locale] = useLocale();
  return useCallback((key: string) => t(key, locale), [locale]);
}
